import {
  Controller,
  Post,
  Get,
  Body,
  Param,
  Headers,
  Req,
  UseGuards,
  HttpCode,
  HttpStatus,
  NotFoundException,
} from '@nestjs/common';
import {
  ApiTags,
  ApiOperation,
  ApiResponse,
  ApiHeader,
  ApiBearerAuth,
  ApiParam,
} from '@nestjs/swagger';
import { PaymentsService } from './payments.service';
import { CreatePaymentIntentDto } from './dto/create-payment-intent.dto';
import { PaymentIntentResponseDto } from './dto/payment-intent-response.dto';
import { OptionalJwtAuthGuard } from '../auth/guards/optional-jwt-auth.guard';
import { CurrentUser } from '../auth/decorators/current-user.decorator';

/**
 * Payments Controller.
 * Handles payment intent initialization, order linking, and transaction queries.
 * Source of truth: PRD.md §6.7 (FR-PAY-1, FR-PAY-2); TECH_STACK.md §8.2, §8.4; TODO.md TASK-026.
 */
@ApiTags('Payments')
@Controller('payments')
export class PaymentsController {
  constructor(private readonly paymentsService: PaymentsService) {}

  @Post('intent')
  @HttpCode(HttpStatus.OK)
  @UseGuards(OptionalJwtAuthGuard)
  @ApiBearerAuth('JWT')
  @ApiOperation({
    summary: 'Initialize payment intent for an order',
    description:
      'Creates a payment order with the active gateway adapter (Razorpay or Mock Sandbox), ' +
      'persists an INITIATED payment transaction, and returns tokens required for mobile checkout.',
  })
  @ApiHeader({
    name: 'Idempotency-Key',
    description: 'Unique client-generated token for safe idempotent retries',
    required: false,
    example: '9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d',
  })
  @ApiResponse({
    status: HttpStatus.OK,
    description: 'Payment intent initialized successfully.',
    type: PaymentIntentResponseDto,
  })
  @ApiResponse({
    status: HttpStatus.NOT_FOUND,
    description: 'Order not found.',
  })
  @ApiResponse({
    status: HttpStatus.CONFLICT,
    description: 'Order is already paid in full.',
  })
  async createPaymentIntent(
    @Body() dto: CreatePaymentIntentDto,
    @CurrentUser() user?: any,
    @Headers('idempotency-key') idempotencyKey?: string,
  ): Promise<PaymentIntentResponseDto> {
    return this.paymentsService.createPaymentIntent(dto, user, idempotencyKey);
  }

  @Post('webhook')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Payment gateway webhook callback',
    description:
      'Listens for server-to-server gateway status callbacks (e.g. payment.captured, payment.failed). ' +
      'Verifies cryptographic signature with webhook secret and idempotently transitions the order to CONFIRMED.',
  })
  @ApiHeader({
    name: 'x-razorpay-signature',
    description: 'Cryptographic HMAC-SHA256 signature generated by Razorpay',
    required: false,
  })
  @ApiHeader({
    name: 'x-webhook-signature',
    description: 'Alternative signature header for sandbox mock testing',
    required: false,
  })
  @ApiResponse({
    status: HttpStatus.OK,
    description: 'Webhook processed successfully or duplicate acknowledged.',
  })
  @ApiResponse({
    status: HttpStatus.BAD_REQUEST,
    description: 'Invalid or missing cryptographic signature.',
  })
  async handleWebhook(
    @Body() body: any,
    @Headers('x-razorpay-signature') razorpaySignature?: string,
    @Headers('x-webhook-signature') customSignature?: string,
    @Headers('signature') genericSignature?: string,
    @Req() req?: any,
  ) {
    const signature = razorpaySignature || customSignature || genericSignature || '';
    const rawPayload = req?.rawBody || body;
    return this.paymentsService.processWebhook(rawPayload, signature);
  }

  @Get(':id')
  @ApiOperation({
    summary: 'Get payment record by ID',
    description: 'Retrieves payment transaction record by its MongoDB ObjectId.',
  })
  @ApiParam({ name: 'id', description: 'MongoDB ObjectId of the payment' })
  @ApiResponse({ status: HttpStatus.OK, description: 'Payment record retrieved.' })
  @ApiResponse({ status: HttpStatus.NOT_FOUND, description: 'Payment not found.' })
  async getPaymentById(@Param('id') id: string) {
    const payment = await this.paymentsService.getPaymentById(id);
    if (!payment) {
      throw new NotFoundException(`Payment record not found with ID: ${id}`);
    }
    return payment;
  }

  @Get('order/:orderId')
  @ApiOperation({
    summary: 'Get payments for an order',
    description: 'Retrieves all payment transactions associated with a given orderId.',
  })
  @ApiParam({ name: 'orderId', description: 'Order tracking ID (e.g. TC402736)' })
  @ApiResponse({
    status: HttpStatus.OK,
    description: 'List of payment records for the order.',
  })
  async getPaymentsByOrderId(@Param('orderId') orderId: string) {
    return this.paymentsService.getPaymentsByOrderId(orderId);
  }
}
